// Re-port the blob construction from the stories file into src/blob.ts, verbatim.
// Usage: node proposals/background-hull/playground/port.mjs packages/gofish-graphics/stories/_proposals/BackgroundHull.stories.tsx
// Each block is found by the line it starts with and copied up to (not including) the line
// that starts the next unrelated definition, minus that definition's leading comment.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(process.argv[2], "utf8").split("\n");
const BLOCKS = [
  // [first line starts with, stop before the line that starts with]
  ["type Pt = [number, number];", "const alphaShape"], // types, samples, cross, convexHull, dist, segIntersect, inPoly
  ["type Poly = Pt[];", "type KelpOpts"], // centerOf, discPoly, bboxOf, segHitsPoly, routeAround, polyLen
  ["const memberRadius", "const blob = "], // memberRadius, EDT, contours, relax, loopArea, segDist2
  ["const signedArea", "const blobInk"],
  ["const erf", "const convolutionBlob"], // section (e): compensation, field, skeleton, smoothBlob
];
const out = [
  "// GENERATED by port.mjs from packages/gofish-graphics/stories/_proposals/BackgroundHull.stories.tsx.",
  "// Verbatim copy of the current blob construction (smoothBlob and its helpers). Do not edit by hand.",
  'import Delaunator from "delaunator";',
  "",
];
for (const [start, stop] of BLOCKS) {
  const a = src.findIndex((l) => l.startsWith(start));
  const b = src.findIndex((l, i) => i > a && l.startsWith(stop));
  if (a < 0 || b < 0) throw new Error(`block ${start} ... ${stop} not found`);
  let e = b;
  while (e > a && /^(\/\*\*| \*|\/\/|\s*$)/.test(src[e - 1])) e--; // drop the next definition's comment
  out.push(...src.slice(a, e), "");
}
out.push(
  "export { smoothBlob, signedArea, loopArea, discPoly, centerOf, memberRadius, dist };",
  "export type { Pt, Member, SmoothOpts, Smooth, Skeleton };",
  ""
);
writeFileSync(join(here, "src/blob.ts"), out.join("\n"));
console.log("wrote src/blob.ts", out.length, "lines");
