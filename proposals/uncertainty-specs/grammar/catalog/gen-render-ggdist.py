# Generates render-ggdist.R from the installed ggdist 3.3.3 vignette sources.
# Every chunk is copied verbatim. Chunks that draw a plot are wrapped so the
# plot is saved to img/ggdist-NN-<slug>.png; the others (data, models) run as is.
# Run from the repo root:
#   python3 proposals/uncertainty-specs/grammar/catalog/gen-render-ggdist.py
import json
import re
import subprocess

DOC = subprocess.run(
    ["Rscript", "-e", 'cat(system.file("doc", package = "ggdist"))'],
    capture_output=True, text=True, check=True,
).stdout.strip()

VIGNETTES = ["slabinterval", "dotsinterval", "lineribbon", "freq-uncertainty-vis"]

# Chunks that are not plots and are not needed (options, printouts, eval=FALSE).
SKIP = {
    "chunk_options", "hidden_options", "reset_options", "priors_fake",
    "parse_dist", "summarized_df", "m_ABC_summary", "m_ABC_coefs",
}
# Chunks that only print a table or a model (no plot) but define data.
NONPLOT = {
    "setup", "sample_data", "dist_data", "priors", "df", "df_2groups",
    "analytical_df", "mtcars_boot", "data_gen", "m_ABC", "m_mpg", "m_iris_v",
}
# Merges: chunk -> entry it joins (differs only in colour/labels).
MERGE = {"stat_lineribbon_gradient_rampbar": "stat_lineribbon_gradient"}


def chunks(path):
    text = open(path).read()
    parts = re.split(r"^## ----(.*)$", text, flags=re.M)
    out = []
    for i in range(1, len(parts), 2):
        header = parts[i]
        label = re.split(r"[,\s-]", header.strip(), maxsplit=1)[0]
        code = parts[i + 1].strip("\n")
        out.append((label, header, code))
    return out


def main():
    lines = [
        "# Renders every plotted chunk of the four ggdist 3.3.3 vignettes",
        "# (slabinterval, dotsinterval, lineribbon, freq-uncertainty-vis) for the",
        "# ggdist catalog (#980). Generated by gen-render-ggdist.py; the chunk code is",
        "# verbatim from system.file('doc', package = 'ggdist'). Run from the repo root:",
        "#   Rscript proposals/uncertainty-specs/grammar/catalog/render-ggdist.R",
        "",
        'img_dir <- "proposals/uncertainty-specs/grammar/catalog/img"',
        "dir.create(img_dir, showWarnings = FALSE, recursive = TRUE)",
        "# the vignettes' size variables (non-pkgdown values)",
        "tiny_width = 5; tiny_height = 3 + 1/3; small_width = 5; small_height = 3 + 1/3",
        "med_width = 5; med_height = 3 + 1/3; large_width = 5.5; large_height = 2/3",
        "save_plot <- function(p, name) {",
        "  ggplot2::ggsave(file.path(img_dir, paste0('ggdist-', name, '.png')), p,",
        "    width = 3.4, height = 2.4, dpi = 110, bg = 'white')",
        "}",
        "",
    ]
    entries = []
    n = 0
    for v in VIGNETTES:
        lines.append(f"# ======== vignette: {v} ========")
        for label, header, code in chunks(f"{DOC}/{v}.R"):
            if label in SKIP:
                continue
            if label in NONPLOT:
                lines += [f"# ---- {label} ----", code, ""]
                if label == "setup":
                    lines.append("theme_set(theme_ggdist(base_size = 7))")
                    lines.append("")
                continue
            if label in MERGE:
                target = next(e for e in entries if e["label"] == MERGE[label])
                name = target["id"] + "b"
                target["merged"].append(label)
                target["extra_imgs"].append(f"img/ggdist-{name}.png")
            else:
                n += 1
                slug = label.replace("_", "-").lower()
                name = f"{n:02d}-{slug}"
                entries.append({
                    "id": name, "label": label, "vignette": v, "header": header,
                    "merged": [], "extra_imgs": [], "img": f"img/ggdist-{name}.png",
                })
            lines += [
                f"# ---- {name} ({v}: {label}) ----",
                f"p <- withVisible({{\n{code}\n}})$value",
                # the chunk sets this option only while it prints; ggsave redraws
                f'withr::with_options(list(ggdist.experimental.slab_data_in_intervals = TRUE), save_plot(p, "{name}"))'
                if "slab_data_in_intervals" in code
                else f'save_plot(p, "{name}")',
                "",
            ]
    src = "\n".join(lines)
    open("proposals/uncertainty-specs/grammar/catalog/render-ggdist.R", "w").write(src)
    json.dump(entries, open("/tmp/ggdist-chunks.json", "w"), indent=1)
    print(n, "entries")


main()
