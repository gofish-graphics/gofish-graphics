// lib v2: the library now ships its own .tooltip().
export class Mark {
  constructor(spec) {
    this.spec = spec;
  }
  name(n) {
    return new Mark({ ...this.spec, name: n });
  }
  label(f) {
    return new Mark({ ...this.spec, label: f });
  }
  tooltip(opts = {}) {
    return new Mark({ ...this.spec, tooltip: { builtin: true, ...opts } });
  }
}
export const rect = (o) => new Mark({ type: "rect", ...o });
