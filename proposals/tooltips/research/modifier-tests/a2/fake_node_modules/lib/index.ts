// A library with one generic attachment point. Written as .ts and compiled
// with the case so the declarations are exact.
export type Modifier<In extends Mark, Out extends Mark = In> = (m: In) => Out;

export class Mark {
  constructor(readonly spec: Record<string, unknown>) {}
  /** Copy with more spec fields; `this` type keeps subclasses. */
  with(fields: Record<string, unknown>): this {
    const C = this.constructor as new (s: Record<string, unknown>) => this;
    return new C({ ...this.spec, ...fields });
  }
  name(n: string): this {
    return this.with({ name: n });
  }
  /** One generic method: apply an imported modifier. */
  use<R extends Mark>(mod: (m: this) => R): R {
    return mod(this);
  }
  /** RxJS-style variadic pipe with overloads up to 3, then a loose fallback. */
  pipe(): this;
  pipe<A extends Mark>(f1: (m: this) => A): A;
  pipe<A extends Mark, B extends Mark>(f1: (m: this) => A, f2: (m: A) => B): B;
  pipe<A extends Mark, B extends Mark, C extends Mark>(
    f1: (m: this) => A,
    f2: (m: A) => B,
    f3: (m: B) => C
  ): C;
  pipe(...fns: ((m: Mark) => Mark)[]): Mark;
  pipe(...fns: ((m: any) => any)[]): Mark {
    return fns.reduce((m, f) => f(m), this as Mark);
  }
}

export class RectMark extends Mark {
  cornerRadius(r: number): this {
    return this.with({ rx: r });
  }
}
export class TextMark extends Mark {
  fontSize(s: number): this {
    return this.with({ fontSize: s });
  }
}
export const rect = (o: Record<string, unknown>) =>
  new RectMark({ type: "rect", ...o });
export const text = (o: Record<string, unknown>) =>
  new TextMark({ type: "text", ...o });

// A built-in modifier, written exactly as a third party would write one.
export const label =
  (field: string) =>
  <M extends Mark>(m: M): M =>
    m.with({ label: field });
