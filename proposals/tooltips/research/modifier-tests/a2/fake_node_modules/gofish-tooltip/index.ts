import { Mark, TextMark } from "lib";

/** Third-party modifier: works on any mark and keeps its precise type. */
export const tooltip =
  (field: string) =>
  <M extends Mark>(m: M): M =>
    m.with({ tooltip: field });

/** Third-party modifier that only makes sense on text marks. */
export const outline =
  (width: number) =>
  (m: TextMark): TextMark =>
    m.with({ outline: width });

/** Wrapping form: tooltipOf(mark, field). */
export const tooltipOf = <M extends Mark>(m: M, field: string): M =>
  m.with({ tooltip: field });
